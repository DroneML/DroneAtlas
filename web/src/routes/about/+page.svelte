			<h1>About DroneATLAS</h1>

			<p>
				DroneATLAS is a web-based exploration platform for multi-sensor drone data, designed to
				support researchers and practitioners working with aerial imagery and sensor data. The
				platform provides interactive map-based tools for visualizing, exploring, and analyzing
				drone-acquired datasets across diverse research domains.
			</p>

			<h2>Project Description</h2>

			<p>
				Drones equipped with multiple sensors (RGB, multispectral, LiDAR, thermal) generate rich
				geospatial datasets that are often difficult to explore interactively. DroneATLAS addresses
				this by providing a unified web interface for browsing, overlaying, and querying multi-sensor
				drone data products, including raster layers derived from drone flights.
			</p>

			<p>
				The platform integrates machine learning capabilities for automated analysis and
				classification of aerial imagery, enabling researchers to rapidly extract insights from
				large-scale drone surveys.
			</p>

